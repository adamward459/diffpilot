/// Seconds since the Unix epoch for `2026-11-25T10:00:01Z`, with optional fractional seconds.
pub fn parse_timestamp(text: &str) -> Option<i64> {
    let text = text.trim().strip_suffix('Z')?;
    let (date, time) = text.split_once('T')?;
    let mut date = date.split('-').map(|part| part.parse::<i64>().ok());
    let (year, month, day) = (date.next()??, date.next()??, date.next()??);
    let time = time.split('.').next()?;
    let mut time = time.split(':').map(|part| part.parse::<i64>().ok());
    let (hour, minute, second) = (time.next()??, time.next()??, time.next()??);
    if !(1..=12).contains(&month) || !(1..=31).contains(&day) || hour > 23 || minute > 59 || second > 60 {
        return None;
    }
    Some(days_from_civil(year, month, day) * 86_400 + hour * 3600 + minute * 60 + second)
}

fn days_from_civil(year: i64, month: i64, day: i64) -> i64 {
    let year = if month <= 2 { year - 1 } else { year };
    let era = year.div_euclid(400);
    let year_of_era = year - era * 400;
    let month_index = (month + 9) % 12;
    let day_of_year = (153 * month_index + 2) / 5 + day - 1;
    let day_of_era = year_of_era * 365 + year_of_era / 4 - year_of_era / 100 + day_of_year;
    era * 146_097 + day_of_era - 719_468
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_github_timestamps() {
        assert_eq!(parse_timestamp("1970-01-01T00:00:00Z"), Some(0));
        assert_eq!(parse_timestamp("2000-03-01T00:00:00Z"), Some(951_868_800));
        assert_eq!(parse_timestamp("2024-02-29T12:30:45Z"), Some(1_709_209_845));
        assert_eq!(parse_timestamp("2026-11-25T10:00:01.1234567Z"), Some(1_795_600_801));
    }

    #[test]
    fn rejects_other_shapes() {
        for text in [
            "",
            "2026-11-25",
            "2026-13-01T00:00:00Z",
            "2026-11-25T10:00:01+02:00",
            "x",
        ] {
            assert_eq!(parse_timestamp(text), None, "{text}");
        }
    }
}
