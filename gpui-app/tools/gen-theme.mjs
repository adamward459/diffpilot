// Regenerates src/diff_pane/highlight/theme_data.rs from the shiki themes the web page used.
// Run from the repo root after `npm ci` in web/: node gpui-app/tools/gen-theme.mjs
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const dist = new URL('../../web/node_modules/@shikijs/themes/dist/', pathToFileURL(process.argv[1]));

const hex = (color) => `0x${color.slice(1, 7).toLowerCase()}`;
const quote = (text) => JSON.stringify(text);

async function table(name, constant) {
  const theme = (await import(new URL(`${name}.mjs`, dist))).default;
  const base = theme.type === 'dark' ? '#d4d4d4' : '#000000';
  const rules = [];
  for (const rule of theme.tokenColors) {
    const color = rule.settings.foreground;
    if (!color || !rule.scope) continue;
    const scopes = Array.isArray(rule.scope) ? rule.scope : [rule.scope];
    rules.push(`    Rule { scopes: ${quote(scopes.join(', '))}, color: ${hex(color)} },`);
  }
  return `pub const ${constant}_FOREGROUND: u32 = ${hex(base)};\npub const ${constant}: &[Rule] = &[\n${rules.join('\n')}\n];\n`;
}

const out = [
  '// Generated by tools/gen-theme.mjs from shiki dark-plus and light-plus. Do not edit.',
  '',
  'pub struct Rule {',
  '    pub scopes: &\'static str,',
  '    pub color: u32,',
  '}',
  '',
  await table('dark-plus', 'DARK_PLUS'),
  await table('light-plus', 'LIGHT_PLUS'),
].join('\n');
writeFileSync(new URL('../src/diff_pane/highlight/theme_data.rs', import.meta.url), out);
